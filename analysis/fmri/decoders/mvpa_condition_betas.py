def decode_loro(X, y, groups, n_perm=N_PERMUTATIONS):
    """
    Linear SVM with Leave-One-Run-Out CV + permutation test.

    Parameters
    ----------
    X      : (n_trials, n_voxels)
    y      : (n_trials,) string labels
    groups : (n_trials,) integer run IDs for LORO splits

    Returns
    -------
    score, perm_scores, p_value, chance
    """
    unique_groups = np.unique(groups)
    if len(unique_groups) < 2:
        n_classes = len(np.unique(y))
        return np.nan, np.array([np.nan]), 1.0, 1.0 / max(n_classes, 1)

    le    = LabelEncoder()
    y_enc = le.fit_transform(y)
    clf   = make_pipeline(StandardScaler(), SVC(kernel='linear', C=1))
    logo  = LeaveOneGroupOut()

    score, perm_scores, p_value = permutation_test_score(
        clf, X, y_enc,
        cv=logo,
        groups=groups,
        n_permutations=n_perm,
        scoring='accuracy',
        random_state=42,
        n_jobs=1,
    )
    chance = 1.0 / len(le.classes_)
    return score, perm_scores, p_value, chance


def decode_cross(X_train, y_train, X_test, y_test, n_perm=N_PERMUTATIONS):
    """
    Train on one set (e.g. A-slot), test on another (e.g. B-slot).
    Permutation test shuffles test labels.

    Returns accuracy, p_value, chance.
    """
    le = LabelEncoder()
    le.fit(np.concatenate([y_train, y_test]))
    clf = make_pipeline(StandardScaler(), SVC(kernel='linear', C=1))
    clf.fit(X_train, le.transform(y_train))
    acc = (clf.predict(X_test) == le.transform(y_test)).mean()

    rng = np.random.default_rng(42)
    perm_accs = []
    for _ in range(n_perm):
        y_shuf = rng.permutation(le.transform(y_test))
        perm_accs.append((clf.predict(X_test) == y_shuf).mean())
    p_value = (np.sum(np.array(perm_accs) >= acc) + 1) / (n_perm + 1)
    chance  = 1.0 / len(le.classes_)
    return acc, p_value, chance



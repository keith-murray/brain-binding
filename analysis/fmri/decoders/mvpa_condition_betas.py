def extract_patterns(beta_4d, roi_mask, vol_indices):
    """
    Extract ROI patterns for specified volume indices.

    Parameters
    ----------
    beta_4d    : (x, y, z, n_trials) array
    roi_mask   : (x, y, z) boolean array
    vol_indices: list/array of int

    Returns
    -------
    X : (n_trials, n_voxels)
    """
    return beta_4d[roi_mask][:, vol_indices].T



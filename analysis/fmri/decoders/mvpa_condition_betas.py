def load_trial_metadata(conditions_file, onsets_file):
    """
    Build a per-trial DataFrame suitable for MVPA analysis.

    GLMsingle metadata provides:
      events_row  : original row index in the full events TSV
      trial_type  : shape name (circle/rectangle/star/triangle)
      block       : main_run1 / main_run2 / main_run3 / main_run4

    Shape onsets TSV provides (indexed by block + trial + phase + position):
      position    : 1/2/3 (within phase)
      phase       : rule / test
      rule_type   : ABA / ABB

    We join on (block, trial_type, phase, position) extracted from the
    onsets TSV row order, which matches the GLMsingle trial order because
    both are sorted chronologically.

    Returns
    -------
    DataFrame with columns:
      vol_idx    : int  — 0-based index into beta 4D volume
      trial_type : str  — shape name
      block      : str  — run block label
      run_id     : int  — integer run number (1–4) for LORO CV
      phase      : str  — 'rule' or 'test'
      position   : int  — 1/2/3
      rule_type  : str  — ABA / ABB
      role       : str  — A / B / Aprime / Bprime (inferred from phase+position)
    """
    # Load GLMsingle metadata
    meta = pd.read_csv(conditions_file, index_col='events_row')
    meta = meta.reset_index()  # keep events_row as a column
    meta.insert(0, 'vol_idx', range(len(meta)))

    # Load shape onsets TSV — one row per stimulus event
    onsets = pd.read_csv(onsets_file, sep='\t')

    # The onsets TSV has 5 rows per trial (5 events).
    # GLMsingle metadata has one row per valid estimable event.
    # We need to match each metadata row to the correct onset row.
    #
    # Strategy: the onsets TSV is sorted by run then onset time,
    # which matches the order GLMsingle received events.
    # We index into onsets using the events_row column from metadata,
    # which is the original row index in the full onsets TSV.
    onsets = onsets.reset_index()  # add 'index' column = original row order
    onsets = onsets.rename(columns={'index': 'events_row'})

    # Merge metadata with onsets on events_row
    merged = meta.merge(
        onsets[['events_row', 'phase', 'position', 'rule_type']],
        on='events_row',
        how='left'
    )

    # Add run_id for LORO CV
    merged['run_id'] = merged['block'].map(BLOCK_TO_RUN)

    # Infer role from phase and position
    # phase=rule, position=1 -> A (first stimulus, A-slot)
    # phase=rule, position=2 -> B (second stimulus, B-slot)
    # phase=rule, position=3 -> A (ABA) or B (ABB) — the repeated stimulus
    # phase=test, position=1 -> Aprime
    # phase=test, position=2 -> Bprime
    def infer_role(row):
        if row['phase'] == 'test':
            return 'Aprime' if row['position'] == 1 else 'Bprime'
        else:  # rule phase
            if row['position'] == 1:
                return 'A'
            elif row['position'] == 2:
                return 'B'
            else:  # position 3
                return 'A' if row['rule_type'] == 'ABA' else 'B'

    merged['role'] = merged.apply(infer_role, axis=1)

    # Warn about any rows that failed to join
    missing = merged['phase'].isna().sum()
    if missing > 0:
        print(f'  Warning: {missing} trials could not be matched to onsets TSV')

    return merged



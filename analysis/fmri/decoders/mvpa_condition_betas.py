def plot_subject(sub_results, sub_cross_results, sub, rois, filename):
    n_rois = len(rois)
    fig, axes = plt.subplots(2, n_rois,
                             figsize=(5 * n_rois, 10),
                             squeeze=False, facecolor='white')

    for ri, roi_name in enumerate(rois):
        # ── Standard decoding ─────────────────────────────────────────────
        ax     = axes[0][ri]
        scores, pvals, labels, chance_val = [], [], [], 0.25

        for a in ANALYSES:
            key = a['name']
            if key in sub_results.get(roi_name, {}):
                r = sub_results[roi_name][key]
                if not np.isnan(r['score']):
                    scores.append(r['score'])
                    pvals.append(r['p_value'])
                    labels.append(key.replace('Shape_', '')
                                     .replace('RuleType_', 'Rule@')
                                     .replace('Role_', 'Role@'))
                    chance_val = r['chance']

        if scores:
            colors = ['steelblue' if p < 0.05 else 'lightsteelblue'
                      for p in pvals]
            x = np.arange(len(scores))
            ax.bar(x, scores, color=colors, alpha=0.85, width=0.6)
            ax.axhline(chance_val, color='red', linestyle='--',
                       linewidth=1.2, label=f'Chance ({chance_val*100:.0f}%)')
